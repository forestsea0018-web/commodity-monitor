# ─── 写一个数据行 ─────────────────────────────────────────────────────────────
def _write_row(ws, ri, vals, fills_by_col, fonts_by_col, aligns_by_col):
    ws.row_dimensions[ri].height = 16
    for ci, v in enumerate(vals, 1):
        cell = ws.cell(row=ri, column=ci, value=v)
        cell.border = BD
        if ci in fills_by_col and fills_by_col[ci]:
            cell.fill = fills_by_col[ci]
        if ci in fonts_by_col:
            cell.font  = fonts_by_col[ci]
        if ci in aligns_by_col:
            cell.alignment = aligns_by_col[ci]


# ─── 标题/表头工具 ────────────────────────────────────────────────────────────
def _make_title(ws, row_n, text, total_cols, fill_hex, font_kw):
    ws.row_dimensions[row_n].height = 30
    ws.merge_cells(f"A{row_n}:{get_column_letter(total_cols)}{row_n}")
    c = ws[f"A{row_n}"]
    c.value = text
    c.font, c.fill, c.alignment = tf(**font_kw), hf(fill_hex), C

def _make_subtitle(ws, row_n, text, total_cols):
    ws.row_dimensions[row_n].height = 18
    ws.merge_cells(f"A{row_n}:{get_column_letter(total_cols)}{row_n}")
    c = ws[f"A{row_n}"]
    c.value = text
    c.font, c.fill, c.alignment = tf(italic=True, color="595959", size=8), hf("D6E4F7"), L

def _make_header(ws, row_n, hdrs):
    ws.row_dimensions[row_n].height = 34
    for ci, h in enumerate(hdrs, 1):
        c = ws.cell(row=row_n, column=ci, value=h)
        c.font, c.fill, c.alignment, c.border = (
            tf(bold=True, color="FFFFFF", size=9), hf("1F3864"), C, BD
        )


